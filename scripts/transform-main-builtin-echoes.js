// scripts/transform-main-builtin-echoes.js
// 把 renderer 端 echoBuiltins/ 子目录（base + 16 张卡片 + index）聚合转译为
// main 端 builtin-echoes.js（CommonJS）。
//
// 用法：  node scripts/transform-main-builtin-echoes.js
//
// === 拼接策略（v2026-07-29 拆分后） ===
//   拆分前：单文件 echoBuiltins.js，字符串替换 import/export。
//   拆分后：src/components/echo/echoBuiltins/ 子目录：
//     - echoBuiltinsBase.js           4 个工厂（baseRender / baseAfterRender / createAnnoSource / buildEchoCard）
//     - echoBuiltins{Nice,Growth,...}.js  16 张卡片各自一文件，文件内 META + `export default buildEchoCard(META)`
//     - echoBuiltins.js               入口：import 16 张 → BUILTIN_ECHO_CARDS = Object.freeze([...])
//
// 本脚本的做法：
//   1) 按顺序 read 各文件
//   2) 把 ES `import ... from '...'` 删掉（base.js 用的是 banner/handlerDoc，
//      而 main 端从 ./builtin-echo-shared.js 取，所以提前 require 并替换引用）
//   3) 把 `export const X = Y` → `const X = Y`，把 `export default buildEchoCard(META)`
//      替换成 `const __card_NN = buildEchoCard(META)` 并 push 到 __allCards 数组
//   4) 把 echoBuiltins.js（聚合文件）里的 `BUILTIN_ECHO_CARDS = Object.freeze([ ... ])`
//      改写为 `BUILTIN_ECHO_CARDS = Object.freeze(__allCards)`
//   5) 末尾统一追加 module.exports
const fs = require('fs')
const path = require('path')

const ROOT = path.join(__dirname, '..', 'src', 'components', 'echo')
const SRC_DIR = path.join(ROOT, 'echoBuiltins')
const DST = path.join(__dirname, '..', 'src-electron', 'main-process', 'service', 'builtin-echoes.js')

const allFiles = fs.readdirSync(SRC_DIR).filter(f => f.endsWith('.js')).sort()
// 顺序：base → 卡片（任何 echoBuiltinsXxx.js，但 ≠ base 与 index） → index
const baseFile = 'echoBuiltinsBase.js'
const indexFile = 'echoBuiltins.js'
const cardFiles = allFiles.filter(f => f !== baseFile && f !== indexFile)
const order = [baseFile, ...cardFiles, indexFile]

let out = ''
// 1) 顶部 helper：注入 banner / handlerDoc
out += `// === auto-generated by scripts/transform-main-builtin-echoes.js ===\n`
out += `// 源码：src/components/echo/echoBuiltins/{base,16 卡片,index}\n`
out += `// 警告：手工同步请用 \`node scripts/transform-main-builtin-echoes.js\` 重新生成。\n\n`
out += `const { banner, handlerDoc } = require('./builtin-echo-shared')\n\n`
out += `const __allCards = []\n\n`

for (const f of order) {
  let src = fs.readFileSync(path.join(SRC_DIR, f), 'utf8')
  src = src.replace(/\r\n/g, '\n')

  // 删 ES import（base.js 用 banner/handlerDoc，已在顶部 require）
  src = src.replace(/^import\s*\{[^}]*\}\s*from\s*['"][^'"]+['"];?\s*$/gm, '')
  src = src.replace(/^import\s+\w+\s+from\s*['"][^'"]+['"];?\s*$/gm, '')

  // 处理 export：
  //   export const X = Y                  → const X = Y
  //   export default buildEchoCard(META)  → 卡片收集到 __allCards
  //   export default { createXxx, ... }   → 删
  //   export function foo() {}            → function foo() {}
  //   export { foo, bar }                 → 删
  src = src.replace(/^export\s+const\s+/gm, 'const ')
  src = src.replace(/^export\s+function\s+/gm, 'function ')

  // 卡片文件：包成 IIFE 避免 `const META` 重复声明。
  // 同时把 default export 转成 `__allCards.push(buildEchoCard(META))`。
  if (f !== baseFile && f !== indexFile) {
    src = src.replace(/^export\s+default\s+buildEchoCard\(META\)\s*$/m, '__allCards.push(buildEchoCard(META))')
    out += `// ===== ${f} =====\n;(() => {\n${src.trim()}\n})()\n\n`
  } else if (f === baseFile) {
    // base.js 末尾的 `export { baseRender, baseAfterRender, createAnnoSource, buildEchoCard }` 删掉
    src = src.replace(/^export\s+\{\s*[^}]+\s*\}\s*$/gm, '')
    out += `// ===== ${f} =====\n${src.trim()}\n\n`
  } else {
    // index.js: `export default BUILTIN_ECHO_CARDS` + `export { BUILTIN_ECHO_CARDS, ... }`
    src = src.replace(/^export\s+default\s+[A-Za-z_]\w*\s*$/gm, '')
    src = src.replace(/^export\s+\{\s*[^}]+\s*\}\s*$/gm, '')
    // index.js 里的 `const BUILTIN_ECHO_CARDS = Object.freeze([...])` 改写为从 __allCards 取
    src = src.replace(
      /const BUILTIN_ECHO_CARDS = Object\.freeze\(\s*\[[\s\S]*?\]\s*\)/,
      'const BUILTIN_ECHO_CARDS = Object.freeze(__allCards)'
    )
    out += `// ===== ${f} =====\n${src.trim()}\n\n`
  }
}

// 末尾追加 module.exports
out = out.trimEnd() + `\n\nmodule.exports = {\n  BUILTIN_ECHO_CARDS,\n  BUILTIN_ECHO_CHANT_IDS,\n  isBuiltinEchoChantId\n}\n`

fs.writeFileSync(DST, out)
console.log('OK:', DST, 'bytes:', out.length)
